// hanvariantgen 基于 OpenCC 双向单字探测，生成 backend/internal/script/tables.go。
//
// 判别规则（对单个 Han 字符 r）：
//   - t2s(r) != r 且 s2t(r) == r：繁体专属（转简后变样，转繁后不变）
//   - s2t(r) != r 且 t2s(r) == r：简体专属
//   - 其余（双向都变或都不变）：简繁共用，不入表
//
// 两栖字（推导判为专属、实则简繁通用）不在生成阶段剔除，
// 由 script 包的 sharedOverride 在运行时构建集合时剔除。
//
// 再生成：cd backend && go run ./cmd/hanvariantgen
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/longbridgeapp/opencc"
)

// hanRanges 参与探测的 Han 区块：常用单字几乎全部落在其中。
var hanRanges = [][2]rune{
	{0x3400, 0x4DBF},   // 扩展 A
	{0x4E00, 0x9FFF},   // CJK 统一表意文字(URO)
	{0xF900, 0xFAFF},   // 兼容表意文字
	{0x20000, 0x2A6DF}, // 扩展 B
}

// chunkRunes 是输出字符串每行的 rune 数，控制行宽约 100 列。
const chunkRunes = 24

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "hanvariantgen:", err)
		os.Exit(1)
	}
}

func run() error {
	out := flag.String("o", defaultOutput(), "输出文件路径")
	flag.Parse()

	t2s, err := opencc.New("t2s")
	if err != nil {
		return fmt.Errorf("构造 t2s 转换器: %w", err)
	}
	s2t, err := opencc.New("s2t")
	if err != nil {
		return fmt.Errorf("构造 s2t 转换器: %w", err)
	}

	hans, hant := derive(t2s, s2t)
	formatted, err := format.Source([]byte(render(hans, hant)))
	if err != nil {
		return fmt.Errorf("格式化生成内容: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("已写入 %s:hansSpecific %d 字,hantSpecific %d 字\n", *out, len(hans), len(hant))
	return nil
}

// defaultOutput 依据运行目录推断默认输出路径：在 backend/ 下运行时按相对路径落盘，
// 否则假定位于仓库根。
func defaultOutput() string {
	if wd, err := os.Getwd(); err == nil && filepath.Base(wd) == "backend" {
		return filepath.Join("internal", "script", "tables.go")
	}
	return filepath.Join("backend", "internal", "script", "tables.go")
}

// convert 包装 OpenCC 转换：出错或空结果一律按「不变」处理，不让个别字符中断推导。
func convert(oc *opencc.OpenCC, in string) string {
	out, err := oc.Convert(in)
	if err != nil || out == "" {
		return in
	}
	return out
}

// derive 遍历 Han 区块做双向单字探测，返回按 rune 升序的简体/繁体专属字符。
func derive(t2s, s2t *opencc.OpenCC) (hans, hant []rune) {
	for _, rg := range hanRanges {
		for r := rg[0]; r <= rg[1]; r++ {
			s := string(r)
			ts := convert(t2s, s)
			st := convert(s2t, s)
			switch {
			case ts != s && st == s:
				hant = append(hant, r) // 繁体专属
			case st != s && ts == s:
				hans = append(hans, r) // 简体专属
			}
		}
	}
	sort.Slice(hans, func(i, j int) bool { return hans[i] < hans[j] })
	sort.Slice(hant, func(i, j int) bool { return hant[i] < hant[j] })
	return hans, hant
}

// render 生成 tables.go 源码。
func render(hans, hant []rune) string {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/hanvariantgen; DO NOT EDIT.\n")
	b.WriteString("// 数据来源：OpenCC v0.3.13 的 t2s/s2t 配置对单字的往返探测（单字输入下词组映射不生效，\n")
	b.WriteString("// 等效于繁简字表比对）。再生成：cd backend && go run ./cmd/hanvariantgen\n")
	b.WriteString("\npackage script\n\n")
	b.WriteString("// 简体专属汉字（升序，推导原始结果）。繁简共用字不入表；\n")
	b.WriteString("// 两栖字保留在表内，由 han.go 的 sharedOverride 在运行时剔除。\n")
	fmt.Fprintf(&b, "const hansSpecificChars = %s\n\n", charsLiteral(hans))
	b.WriteString("// 繁体专属汉字（升序，推导原始结果）。繁简共用字不入表；\n")
	b.WriteString("// 两栖字保留在表内，由 han.go 的 sharedOverride 在运行时剔除。\n")
	fmt.Fprintf(&b, "const hantSpecificChars = %s\n\n", charsLiteral(hant))
	return b.String()
}

// charsLiteral 把 rune 序列折行为多段字符串常量的拼接表达式，内容按 rune 升序。
func charsLiteral(rs []rune) string {
	if len(rs) == 0 {
		return `""`
	}
	parts := make([]string, 0, len(rs)/chunkRunes+1)
	for i := 0; i < len(rs); i += chunkRunes {
		end := min(i+chunkRunes, len(rs))
		parts = append(parts, strconv.Quote(string(rs[i:end])))
	}
	return strings.Join(parts, " +\n\t")
}
